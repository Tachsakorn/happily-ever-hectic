import type { LevelDef, LevelGuestSpec, WeddingDef } from '../../../content/types';

type GuestOpts = Partial<Pick<LevelGuestSpec, 'bringsGift' | 'likes' | 'dislikes'>>;

/** Compact guest-list helper; the result is plain data. */
export function guest(
  key: string,
  name: string,
  typeId: string,
  groupId: string,
  arriveAt: number,
  opts: GuestOpts = {},
): LevelGuestSpec {
  return {
    key,
    name,
    typeId,
    groupId,
    arriveAt,
    bringsGift: opts.bringsGift ?? false,
    likes: opts.likes ?? [],
    dislikes: opts.dislikes ?? [],
  };
}

